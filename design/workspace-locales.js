export function translate(text, language = 'zh-CN', values = {}) {
  const source = String(text ?? '');
  const translated = language === 'zh-CN' ? source : UI_COPY[source]?.[language] || source;
  return translated.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}
